#!/usr/bin/env bun
/**
 * Writes src/vendor/nunjucks-source.ts: the Nunjucks browser bundle as a
 * string, evaluated inside QuickJS (never on the host). Committed, so the
 * package works from source without a build; re-run after a version bump and
 * update the pinned digest.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "3.2.4";
const SHA256 = "93769288b3eb63fff02d40406ba4d2d49f48b70f31576cdc330ee7f626856f3f";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("nunjucks/package.json"));
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
if (version !== VERSION) throw new Error(`nunjucks ${version} installed, expected ${VERSION}`);
const source = readFileSync(join(pkgDir, "browser", "nunjucks.min.js"), "utf8");
const digest = createHash("sha256").update(source).digest("hex");
if (digest !== SHA256) throw new Error(`nunjucks.min.js digest ${digest}, expected ${SHA256}`);
const license = readFileSync(join(pkgDir, "LICENSE"), "utf8").trim();

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "vendor", "nunjucks-source.ts");
writeFileSync(
  out,
  `// Generated by scripts/vendor-nunjucks.ts from nunjucks@${VERSION} (browser/nunjucks.min.js, sha256 ${digest}). Do not edit.\n` +
    `/*\n${license}\n*/\n` +
    `export const NUNJUCKS_VERSION = ${JSON.stringify(VERSION)};\n` +
    `export const NUNJUCKS_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`wrote ${out} (${source.length} chars, sha256 ${digest})`);
