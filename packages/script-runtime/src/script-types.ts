/**
 * Ambient types for script authors (`atlcli.d.ts`), written next to scripts by
 * `atlcli script init`. Kept as a string so every host (CLI, browser editor)
 * ships the same contract; `script-types.test.ts` keeps it in step with the verbs.
 */
export const ATLCLI_SCRIPT_TYPES = `// Generated by \`atlcli script init\`. Types for the atlcli script runtime.
// Scripts run in a sandbox: no fetch, no imports, no Node APIs. Writes are
// planned, not executed, until the plan is applied.
export {};

declare global {
type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

type ScriptPermission =
  | "jira:read"
  | \`jira:write:\${string}\`
  | "confluence:read"
  | \`confluence:write:\${string}\`;

interface ScriptParamSpec {
  type: "string" | "number" | "boolean";
  default?: string | number | boolean;
  description?: string;
}

/** Shape of \`export const meta\`. */
interface ScriptMeta {
  /** Lowercase letters, digits and dashes; defaults to the file name. */
  name?: string;
  description?: string;
  /** Once given, everything else is denied. Write grants name one project or space, e.g. "jira:write:ATLCLI". */
  permissions?: ScriptPermission[];
  /** Planned writes per run (default 10000; per issue with --each: 50). */
  limits?: { maxWrites?: number };
  /** Parameters passed with \`--param name=value\`. */
  params?: Record<string, ScriptParamSpec>;
  /**
   * Per-issue mode (\`atlcli script run file.ts --each\`): \`export default async (issue, params) => …\`
   * runs once per issue of \`jql\` (\`--each "<jql>"\` overrides it). Each issue comes
   * with \`fields\` (default: summary, status, assignee, priority, issuetype, labels).
   */
  each?: { jql?: string; fields?: string[] };
}

interface JiraIssue {
  id: string;
  key: string;
  /** Raw Jira fields; \`updated\` is always present. */
  fields: { updated: string; [field: string]: Json };
  /** Issue properties asked for with \`search(jql, { properties })\`, when set. */
  properties?: Record<string, Json>;
}

interface ConfluencePageRef {
  id: string;
  title: string;
  spaceKey: string;
}

interface ConfluencePage extends ConfluencePageRef {
  version: number;
  parentId?: string;
  markdown: string;
}

/** A page as stored (storage XHTML), for lossless copies; \`properties\` holds its \`atlcli.*\` content properties. */
interface ConfluencePageStorage extends ConfluencePageRef {
  version: number;
  parentId?: string;
  storage: string;
  properties: Record<string, Json>;
}

/** Ids and keys of objects a plan creates read \`plan:<n>\` until the plan is applied. */
type PlannedRef = string;

interface JiraBoard {
  id: number;
  name: string;
  /** "scrum", "kanban" or "simple" */
  type: string;
  projectKey?: string;
}

interface JiraSprint {
  id: number;
  name: string;
  state: "future" | "active" | "closed";
  boardId?: number;
  startDate?: string;
  endDate?: string;
  goal?: string;
}

interface ConfluenceComment {
  id: string;
  authorId?: string;
  created?: string;
  status: string;
  markdown: string;
  replies: ConfluenceComment[];
}

interface ConfluenceAttachment {
  id: string;
  name: string;
  mediaType: string;
  size: number;
  version: number;
}

/** File content made by the script (up to 10 MB); there is no file system access. */
interface AttachmentInput {
  name: string;
  /** Text, or base64 with \`encoding: "base64"\`. */
  content: string;
  encoding?: "utf8" | "base64";
}

/** Set while transitioning: screen fields (raw Jira values) and a Markdown comment. */
interface TransitionOptions {
  fields?: Record<string, Json>;
  comment?: string;
}

/** ISO 8601 with offset, e.g. "2026-11-02T09:00:00.000Z". */
type IsoDate = string;

/** Output goes to the terminal (stderr), not into the plan. */
const console: {
  log(...values: unknown[]): void;
  info(...values: unknown[]): void;
  warn(...values: unknown[]): void;
  error(...values: unknown[]): void;
};

const atlcli: {
  /** Values passed with \`--param name=value\` (typed when declared in meta.params). */
  readonly params: Readonly<Record<string, string | number | boolean>>;
  /**
   * Renders a Jinja template (tolerant) with \`--var\`/\`--vars-file\` values
   * and the frozen \`--now\`. A string is plain text unless \`format\` says
   * otherwise; an object with \`type: "doc"\` is ADF. Unresolved \`{{…}}\` stays
   * literal and is reported in the plan; with \`--strict\` it fails the run.
   */
  render<T>(
    input: T,
    options?: {
      vars?: Record<string, unknown>;
      format?: "text" | "adf" | "storage" | "wikimarkup";
      source?: unknown;
      parent?: unknown;
      unit?: string;
      /** Checks a rendered text value as this Jira field kind (a label must not contain whitespace, …). */
      kind?: "summary" | "label" | "name" | "string" | "number" | "date" | "option";
    },
  ): Promise<T>;
  readonly jira: {
    /** All issues matching \`jql\`, paged transparently. */
    search(jql: string, options?: { fields?: string[]; properties?: string[]; limit?: number }): AsyncIterable<JiraIssue>;
    get(key: string, options?: { fields?: string[] }): Promise<JiraIssue>;
    /**
     * Read-only escape hatch: GET any Jira REST resource of the site, e.g.
     * rest("/rest/api/3/field") or rest("/rest/api/3/issue/A-1/changelog", { query: { maxResults: 100 } }).
     * No writes; responses up to 5 MB. Needs jira:read.
     */
    rest(path: string, options?: { query?: Record<string, string | number | boolean> }): Promise<Json>;
    /**
     * \`description\` is Markdown. To copy a description losslessly, pass the
     * raw value from \`get\`/\`search\` as \`fields.description\` instead (not both).
     * \`properties\` are issue properties set on create, by key.
     */
    create(input: {
      project: string;
      type: string;
      summary: string;
      description?: string;
      fields?: Record<string, Json>;
      properties?: Record<string, Json>;
    }): Promise<{ id: PlannedRef; key: PlannedRef }>;
    update(key: string, input: { summary?: string; description?: string; fields?: Record<string, Json> }): Promise<null>;
    /**
     * Transition by name (case-insensitive); checked when the plan is made.
     * \`fields\` are set on the transition screen (e.g. \`{ resolution: { name: "Done" } }\`),
     * \`comment\` (Markdown) is added with the transition.
     */
    transition(key: string, to: string, options?: TransitionOptions): Promise<null>;
    /**
     * Best effort, for issues whose workflow is not known yet (e.g. created by
     * this plan): on apply, takes a direct transition into \`status\` if one is
     * available, else changes nothing (the apply report says moved: false).
     */
    setStatus(key: string, status: string, options?: TransitionOptions): Promise<null>;
    /** Transitions available now, with the status each leads to (category: "new" | "indeterminate" | "done"). */
    transitions(key: string): Promise<Array<{ name: string; to: { name: string; category?: string } }>>;
    /** Changes from the issue's history, oldest first; \`fields\` limits them (e.g. \`["status"]\`). */
    history(key: string, options?: { fields?: string[] }): Promise<Array<{ at: IsoDate; author?: string; field: string; from: string | null; to: string | null }>>;
    watchers(key: string): Promise<Array<{ accountId?: string; displayName?: string }>>;
    /** \`user\`: "me", an email, a display name or an account id. Skipped when already watching. */
    addWatcher(key: string, user: string): Promise<null>;
    /** Skipped when not watching. */
    removeWatcher(key: string, user: string): Promise<null>;
    /**
     * Jira sends an e-mail about the issue (on apply). Name at least one recipient;
     * \`users\` are resolved like \`assign\`.
     */
    notify(
      key: string,
      input: {
        subject: string;
        markdown: string;
        to: { users?: string[]; groups?: string[]; reporter?: boolean; assignee?: boolean; watchers?: boolean; voters?: boolean };
      },
    ): Promise<null>;
    /** A string is Markdown; \`{ raw }\` is the site's own format (ADF on Cloud, as \`get\` returns it), sent unchanged. */
    comment(key: string, body: string | { raw: Json }): Promise<{ id: PlannedRef }>;
    /** Reads as a sentence: link("A-1", "blocks", "A-2"). \`type\` is a link type name or either of its phrases. */
    link(from: string, type: string, to: string): Promise<null>;
    /** "me", an email, a display name or an account id; \`null\` unassigns. */
    assign(key: string, user: string | null): Promise<null>;
    addLabels(key: string, labels: string[]): Promise<null>;
    removeLabels(key: string, labels: string[]): Promise<null>;
    attach(key: string, file: AttachmentInput): Promise<{ id: PlannedRef }>;
    /**
     * Copies attachment \`id\` (from \`fields.attachment\`) to \`toIssue\`. The bytes are
     * copied on apply and never enter the script or the plan, so there is no
     * size cap. Skipped when \`toIssue\` already has a file of that name and size.
     */
    copyAttachment(id: string, toIssue: string): Promise<{ id: PlannedRef | string }>;
    boards(options?: { project?: string; name?: string; limit?: number }): AsyncIterable<JiraBoard>;
    sprints(boardId: number, options?: { state?: "future" | "active" | "closed"; limit?: number }): AsyncIterable<JiraSprint>;
    /** Needs a scrum board. */
    createSprint(input: { board: number; name: string; goal?: string; startDate?: IsoDate; endDate?: IsoDate }): Promise<{ id: PlannedRef }>;
    /** \`state: "active"\` starts a future sprint, \`"closed"\` completes an active one. */
    updateSprint(
      id: number | PlannedRef,
      input: { name?: string; goal?: string; startDate?: IsoDate; endDate?: IsoDate; state?: "active" | "closed" },
    ): Promise<null>;
    moveToSprint(sprintId: number | PlannedRef, keys: string[]): Promise<null>;
  };
  readonly confluence: {
    /** All pages matching \`cql\`, paged transparently. */
    search(cql: string, options?: { limit?: number }): AsyncIterable<ConfluencePageRef>;
    /**
     * Read-only escape hatch below the Confluence base: "/rest/api/…" or "/api/v2/…",
     * e.g. rest("/api/v2/pages/123/properties"). No writes; up to 5 MB. Needs confluence:read.
     */
    rest(path: string, options?: { query?: Record<string, string | number | boolean> }): Promise<Json>;
    getPage(id: string): Promise<ConfluencePage>;
    getPage(id: string, options: { storage: true }): Promise<ConfluencePageStorage>;
    /** Direct child pages, in page-tree order. */
    children(id: string): Promise<ConfluencePageRef[]>;
    /** \`markdown\` is converted; \`storage\` is sent as is (pass exactly one). \`properties\` are content properties. */
    createPage(
      input: { space: string; title: string; parentId?: string; properties?: Record<string, Json> } & ({ markdown: string } | { storage: string }),
    ): Promise<{ id: PlannedRef }>;
    /** Keeps the current title unless \`title\` is given. */
    updatePage(id: string, input: { title?: string; markdown: string }): Promise<{ id: string }>;
    /** Updates the page with this exact title in \`space\`, or creates it. */
    upsertPage(input: { space: string; title: string; markdown: string; parentId?: string }): Promise<{ id: PlannedRef; created: boolean }>;
    addLabels(pageId: string, labels: string[]): Promise<null>;
    removeLabels(pageId: string, labels: string[]): Promise<null>;
    /** Footer comments with replies. */
    comments(pageId: string): Promise<ConfluenceComment[]>;
    /** Adds a footer comment; \`markdown\` is converted. */
    comment(pageId: string, markdown: string): Promise<{ id: PlannedRef }>;
    /** Within the page's space. */
    movePage(id: string, input: { parentId: string }): Promise<{ id: string }>;
    /** Moves the page to the space's trash. */
    deletePage(id: string): Promise<null>;
    attachments(pageId: string): Promise<ConfluenceAttachment[]>;
    /** Replaces an attachment of the same name with a new version. */
    attach(pageId: string, file: AttachmentInput): Promise<{ id: PlannedRef }>;
    /** Copies an attachment to another page host-side (bytes never enter the plan); skipped when the target has it. */
    copyAttachment(attachmentId: string, sourcePageId: string, toPageId: string): Promise<{ id: string }>;
    /** Writes a local file when the plan is applied; \`path\` is relative (default "<id>.<format>"). */
    export(pageId: string, options: { format: "pdf" | "docx"; path?: string }): Promise<{ path: string }>;
  };
};
}
`;
